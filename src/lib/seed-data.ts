function makePresetArtwork(
  emoji: string,
  title: string,
  subtitle: string,
  bg1: string,
  bg2: string
): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="450" viewBox="0 0 800 450">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="${bg1}"/>
      <stop offset="100%" stop-color="${bg2}"/>
    </linearGradient>
    <pattern id="dots" width="28" height="28" patternUnits="userSpaceOnUse">
      <circle cx="14" cy="14" r="2" fill="rgba(255,255,255,0.16)"/>
    </pattern>
  </defs>
  <rect width="800" height="450" fill="url(#g)"/>
  <rect width="800" height="450" fill="url(#dots)"/>
  <circle cx="400" cy="175" r="88" fill="rgba(255,255,255,0.18)"/>
  <text x="400" y="205" text-anchor="middle" font-size="96">${emoji}</text>
  <text x="400" y="325" text-anchor="middle" font-family="sans-serif" font-weight="800" font-size="34" fill="#FFFFFF">${title}</text>
  <text x="400" y="370" text-anchor="middle" font-family="sans-serif" font-weight="600" font-size="22" fill="rgba(255,247,237,0.92)">${subtitle}</text>
</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

